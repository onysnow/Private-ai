"""Write the list of file formats OpenAleph's ingest-file reads (ADR-0006).

    python tools/openaleph_ingest_formats.py            # ingest-file 5.3.1
    python tools/openaleph_ingest_formats.py --tag 5.4.0

Reads the ingestor classes inside the ``ghcr.io/openaleph/ingest-file``
image (Docker, no network) and writes
``backend/app/services/openaleph_formats.py``: every ingestor in the order
ingest-file's ``Manager.auction`` tries them, with its score and the MIME
types and file extensions it claims, normalised the way ``Ingestor.match``
normalises them (rigour's ``normalize_mimetype`` and
``normalize_extension``). The auction gives a file to the highest-scoring
ingestor that claims it; ``IgnoreIngestor`` stores a file without reading
it, so a format whose auction it wins (executables, fonts, keys, logs...)
is not offered. Run it again when the OpenAleph version changes; a backend
test fails until you do.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "backend" / "app" / "services" / "openaleph_formats.py"
IGNORE = "IgnoreIngestor"

# Runs inside the image: the ingestor registry Manager.auction iterates
# (servicelayer's get_extensions("ingestors"), from ingest-file's entry points).
PROBE = r"""
import json
from rigour.mime import normalize_extension, normalize_mimetype
from servicelayer.extensions import get_extensions
from ingestors import __version__
rows = []
for cls in get_extensions("ingestors"):
    mimes = sorted({m for m in (normalize_mimetype(x, default=None) for x in getattr(cls, "MIME_TYPES", [])) if m})
    exts = sorted({e for e in (normalize_extension(x) for x in getattr(cls, "EXTENSIONS", [])) if e})
    rows.append({"name": cls.__name__, "score": cls.SCORE, "mime_types": mimes, "extensions": exts})
print(json.dumps({"version": __version__, "ingestors": rows}))
"""


def probe(tag: str) -> dict[str, Any]:
    result = subprocess.run(
        ["docker", "run", "--rm", "--network", "none", "--entrypoint", "python",
         f"ghcr.io/openaleph/ingest-file:{tag}", "-c", PROBE],
        check=True, capture_output=True, text=True,
    )
    return json.loads(result.stdout.strip().splitlines()[-1])


def winner(ingestors: list[dict[str, Any]], *, mime_type: str | None = None, extension: str | None = None) -> str | None:
    """Manager.auction for one MIME type or one extension: the first
    ingestor with the highest score above zero that claims it."""
    best_score, best = 0, None
    for row in ingestors:
        claims = (mime_type is not None and mime_type in row["mime_types"]) or (
            extension is not None and extension in row["extensions"])
        if claims and row["score"] > best_score:
            best_score, best = row["score"], row["name"]
    return best


def _set(name: str, values: list[str]) -> list[str]:
    lines = [f"{name}: frozenset[str] = frozenset({{"]
    lines += [f"    {value!r}," for value in values]
    return [*lines, "})"]


def render(tag: str, found: dict[str, Any]) -> str:
    ingestors = found["ingestors"]
    mimes = sorted({m for row in ingestors for m in row["mime_types"]
                    if winner(ingestors, mime_type=m) not in (None, IGNORE)})
    exts = sorted({e for row in ingestors for e in row["extensions"]
                   if winner(ingestors, extension=e) not in (None, IGNORE)})
    lines = [
        '"""File formats OpenAleph\'s ingest-file reads (ADR-0006, Wave A).',
        "",
        "Generated by tools/openaleph_ingest_formats.py from the ingestor classes in",
        f"ghcr.io/openaleph/ingest-file:{tag} (ingest-file {found['version']}). Do not edit",
        "by hand; run the tool again when the OpenAleph version changes.",
        '"""',
        "",
        f'INGEST_FILE_IMAGE = "ghcr.io/openaleph/ingest-file:{tag}"',
        "# Stores a file without reading it.",
        f'IGNORE = "{IGNORE}"',
        "",
        "# (name, score, MIME types, extensions), in the order Manager.auction",
        "# tries them: the first ingestor with the highest score that claims a",
        "# file's MIME type or extension reads it.",
        "INGESTORS: tuple[tuple[str, int, frozenset[str], frozenset[str]], ...] = (",
    ]
    for row in ingestors:
        mime_set = "frozenset({" + ", ".join(repr(m) for m in row["mime_types"]) + "})" if row["mime_types"] else "frozenset()"
        ext_set = "frozenset({" + ", ".join(repr(e) for e in row["extensions"]) + "})" if row["extensions"] else "frozenset()"
        lines.append(f"    ({row['name']!r}, {row['score']}, {mime_set}, {ext_set}),")
    lines += [")", "", "# MIME types an ingestor other than IgnoreIngestor wins on its own."]
    lines += _set("MIME_TYPES", mimes)
    lines += ["", "# Extensions (lower-case, no dot) an ingestor other than IgnoreIngestor wins on their own."]
    lines += _set("EXTENSIONS", exts)
    return "\n".join([*lines, ""])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tag", default="5.3.1", help="ingest-file image tag (default 5.3.1)")
    args = parser.parse_args()
    TARGET.write_text(render(args.tag, probe(args.tag)), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
